-- 원본 수정/삭제와 독립적인 제출본 보관. 기존 제출에 당시 내용이 없으면 자동 이관하지 않는다.
BEGIN;
CREATE TABLE IF NOT EXISTS public.project_application_portfolio_snapshots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_portfolio_id BIGINT NOT NULL UNIQUE REFERENCES public.project_application_portfolios(id),
 source_portfolio_id BIGINT NOT NULL,
 title VARCHAR(255) NOT NULL,
 content JSONB NOT NULL CHECK (jsonb_typeof(content)='object'),
 created_at TIMESTAMP NOT NULL,
 updated_at TIMESTAMP NOT NULL
);
DO $$ DECLARE c record; BEGIN
 IF EXISTS(SELECT 1 FROM public.project_application_portfolios l
  LEFT JOIN public.project_application_portfolio_snapshots s ON s.application_portfolio_id=l.id
  WHERE s.id IS NULL OR s.source_portfolio_id IS DISTINCT FROM l.portfolio_id AND l.portfolio_id IS NOT NULL) THEN
  RAISE EXCEPTION '제출 당시 보관본 없는 이력은 자동 이관할 수 없습니다. 기존 제출을 먼저 확인하세요.';
 END IF;
 ALTER TABLE public.project_application_portfolios ALTER COLUMN portfolio_id DROP NOT NULL;
 FOR c IN SELECT p.conname FROM pg_constraint p
  JOIN pg_attribute a ON a.attrelid=p.conrelid AND a.attnum=p.conkey[1]
  WHERE p.conrelid='public.project_application_portfolios'::regclass AND p.confrelid='public.portfolios'::regclass
   AND p.contype='f' AND array_length(p.conkey,1)=1 AND a.attname='portfolio_id'
 LOOP
  EXECUTE format('ALTER TABLE public.project_application_portfolios DROP CONSTRAINT %I',c.conname);
 END LOOP;
 ALTER TABLE public.project_application_portfolios ADD CONSTRAINT fk_project_application_portfolio
  FOREIGN KEY(portfolio_id) REFERENCES public.portfolios(id) ON DELETE SET NULL;
END $$;
CREATE INDEX IF NOT EXISTS ix_project_application_portfolio ON public.project_application_portfolios(portfolio_id);
COMMIT;
