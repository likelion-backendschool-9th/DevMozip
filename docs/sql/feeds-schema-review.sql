-- 검토/수동 적용용. 2026-11-09 공유 개발 DB에 적용 완료. 재실행하지 않는다.
-- 근거: feat/91-feeds의 docs/feed-plan.md(2026-11-09).
-- reports와 같은 IDENTITY/TIMESTAMP/외래키 형식. 사용자 위임으로 feeds/feed_likes 명칭 확정.
-- 이미 테이블이 있으면 오류로 중단한다. DROP/ALTER/샘플 데이터 삽입 없음.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.feeds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL REFERENCES public.users(id),
    original_feed_id BIGINT REFERENCES public.feeds(id),
    type VARCHAR(20) NOT NULL,       -- POST / REPOST
    category VARCHAR(30) NOT NULL,  -- INFO / FEEDBACK / PROMO / COMMUNITY
    title VARCHAR(150),             -- POST 필수, REPOST NULL: 서비스에서 검증
    content TEXT,                   -- 원본 본문 필수/퍼가기 의견 선택: 서비스에서 검증
    tech_stacks JSONB NOT NULL DEFAULT '[]'::jsonb,
    interests JSONB NOT NULL DEFAULT '[]'::jsonb,
    image_urls JSONB NOT NULL DEFAULT '[]'::jsonb,
    view_count BIGINT NOT NULL DEFAULT 0,
    visibility VARCHAR(20) NOT NULL, -- VISIBLE / HIDDEN
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX feeds_created_id_idx ON public.feeds(created_at DESC, id DESC);
CREATE INDEX feeds_author_created_idx ON public.feeds(author_id, created_at DESC, id DESC);
CREATE INDEX feeds_original_idx ON public.feeds(original_feed_id);

COMMENT ON TABLE public.feeds IS '게시글 및 퍼간 글';
COMMENT ON COLUMN public.feeds.author_id IS '작성자 사용자 ID';
COMMENT ON COLUMN public.feeds.original_feed_id IS '퍼간 글의 원본 feeds.id';
COMMENT ON COLUMN public.feeds.image_urls IS '서버에 저장한 이미지의 경로 배열. 파일 바이너리는 저장하지 않음';
COMMENT ON COLUMN public.feeds.deleted_at IS '논리 삭제 시각';
COMMIT;
