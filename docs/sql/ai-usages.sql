-- STEP 7: AI tables only. Apply explicitly before deploying the new application.
-- Shared PostgreSQL 17.11 was inspected read-only: ai_usages and both request columns were absent.
-- This script has NOT been applied to the shared DB.
-- Historical requests remain uncharged (both added columns are NULL).
BEGIN;
CREATE TABLE IF NOT EXISTS ai_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    usage_month CHAR(7) NOT NULL,
    used_count INT NOT NULL DEFAULT 0,
    pending_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
ALTER TABLE ai_usages ADD COLUMN IF NOT EXISTS pending_count INT NOT NULL DEFAULT 0;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='ai_usages'::regclass AND conname='uk_ai_usage_month') THEN
        ALTER TABLE ai_usages ADD CONSTRAINT uk_ai_usage_month UNIQUE (user_id, usage_month);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='ai_usages'::regclass AND conname='ck_ai_usage_nonnegative') THEN
        ALTER TABLE ai_usages ADD CONSTRAINT ck_ai_usage_nonnegative CHECK (used_count >= 0 AND pending_count >= 0);
    END IF;
END $$;
ALTER TABLE ai_recommendation_requests ADD COLUMN IF NOT EXISTS ai_usage_id BIGINT;
ALTER TABLE ai_recommendation_requests ADD COLUMN IF NOT EXISTS reservation_expires_at TIMESTAMP WITHOUT TIME ZONE;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='ai_recommendation_requests'::regclass AND conname='fk_ai_request_usage') THEN
        ALTER TABLE ai_recommendation_requests ADD CONSTRAINT fk_ai_request_usage FOREIGN KEY (ai_usage_id) REFERENCES ai_usages(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='ai_recommendation_requests'::regclass AND conname='ck_ai_request_reservation') THEN
        ALTER TABLE ai_recommendation_requests ADD CONSTRAINT ck_ai_request_reservation CHECK (
            (ai_usage_id IS NULL AND reservation_expires_at IS NULL) OR
            (ai_usage_id IS NOT NULL AND reservation_expires_at IS NOT NULL)
        );
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_ai_request_usage_pending ON ai_recommendation_requests(ai_usage_id, id) WHERE status='PENDING';
COMMIT;
