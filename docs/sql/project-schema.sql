-- 프로젝트 청사진 기준. 외부 users/portfolios/review_keywords/chat_members FK는 결합 시 추가.
-- 기존 테이블이 있으면 오류로 중단한다. 재실행용 IF NOT EXISTS로 불일치를 숨기지 않는다.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
CREATE TABLE public.projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 host_member_id BIGINT NOT NULL,
 title VARCHAR(255) NOT NULL,
 summary VARCHAR(255),
 description TEXT NOT NULL,
 goal TEXT,
 recruitment_slots JSONB NOT NULL,
 tech_stacks JSONB NOT NULL,
 interests JSONB NOT NULL,
 image_url VARCHAR(2048) NOT NULL,
 is_public BOOLEAN NOT NULL,
 status VARCHAR(30) NOT NULL,
 view_count BIGINT NOT NULL DEFAULT 0,
 recruitment_start DATE NOT NULL,
 recruitment_end DATE NOT NULL,
 development_start DATE NOT NULL,
 development_end DATE NOT NULL,
 completed_at TIMESTAMP WITHOUT TIME ZONE,
 deleted_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE public.project_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES public.projects(id),
 applicant_member_id BIGINT NOT NULL,
 job_role VARCHAR(50) NOT NULL,
 introduction TEXT,
 status VARCHAR(20) NOT NULL,
 rejection_reason VARCHAR(200),
 applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 processed_at TIMESTAMP WITHOUT TIME ZONE,
 cancelled_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(project_id, applicant_member_id)
);
CREATE TABLE public.project_application_portfolios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES public.project_applications(id),
 portfolio_id BIGINT,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(application_id, portfolio_id)
);
CREATE TABLE public.project_members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES public.projects(id),
 user_id BIGINT NOT NULL,
 role VARCHAR(20) NOT NULL,
 job_role VARCHAR(50),
 status VARCHAR(20) NOT NULL,
 joined_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 left_at TIMESTAMP WITHOUT TIME ZONE,
 end_requested_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(project_id, user_id)
);
CREATE TABLE public.member_removal_votes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES public.projects(id),
 proposer_member_id BIGINT NOT NULL REFERENCES public.project_members(id),
 target_member_id BIGINT NOT NULL REFERENCES public.project_members(id),
 reason TEXT NOT NULL,
 eligible_voter_count INTEGER NOT NULL,
 status VARCHAR(20) NOT NULL,
 expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 resolved_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE public.member_removal_ballots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vote_id BIGINT NOT NULL REFERENCES public.member_removal_votes(id),
 voter_member_id BIGINT NOT NULL REFERENCES public.project_members(id),
 agree BOOLEAN,
 voted_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(vote_id, voter_member_id)
);
CREATE TABLE public.reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES public.projects(id),
 reviewer_member_id BIGINT NOT NULL REFERENCES public.project_members(id),
 reviewee_member_id BIGINT NOT NULL REFERENCES public.project_members(id),
 status VARCHAR(20) NOT NULL,
 token_hash VARCHAR(255) NOT NULL,
 expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 rating INTEGER,
 selected_keywords JSONB NOT NULL,
 submitted_at TIMESTAMP WITHOUT TIME ZONE,
 last_reminded_at TIMESTAMP WITHOUT TIME ZONE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(project_id, reviewer_member_id, reviewee_member_id)
);
COMMIT;
