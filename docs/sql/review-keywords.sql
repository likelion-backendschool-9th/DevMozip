-- 리뷰 키워드 원본. 기존 reviews 및 다른 테이블은 변경하지 않는다.
-- 수동 적용용이며 애플리케이션 시작 시 자동 실행하지 않는다.
BEGIN;
CREATE TABLE IF NOT EXISTS public.review_keywords (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
 CONSTRAINT review_keywords_name_valid CHECK (name = btrim(name) AND char_length(name) > 0)
);
-- 기존 Mock에서 사용하던 기본 선택지. 재실행해도 기존 이름/활성 상태를 수정하지 않는다.
INSERT INTO public.review_keywords(name) VALUES
 ('소통이 원활해요'),('약속을 잘 지켜요'),('문제 해결이 뛰어나요'),('함께 성장해요')
ON CONFLICT(name) DO NOTHING;
COMMIT;
