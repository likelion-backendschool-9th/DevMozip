 ('지식을 아낌없이 공유해요'),
 ('책임감 있게 완수해요'),
 ('일정을 체계적으로 관리해요'),
 ('코드를 깔끔하게 작성해요'),
 ('문서를 알기 쉽게 정리해요'),
 ('새로운 아이디어를 제안해요'),
 ('동료의 의견을 존중해요'),
 ('꾸준히 학습하고 성장해요'),
 ('어려운 상황에도 적극적이에요')
ON CONFLICT(name) DO NOTHING;
-- 원본에서 찾지 못한 기존 선택값이나 제한 초과 데이터가 있으면 자동 변경하지 않고 전체 중단한다.
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='reviews' AND column_name='selected_keywords') THEN
 IF EXISTS (SELECT 1 FROM public.reviews WHERE jsonb_array_length(selected_keywords)>5) THEN
  RAISE EXCEPTION '기존 리뷰에 5개를 초과한 선택값이 있습니다.';
 END IF;
 IF EXISTS (SELECT 1 FROM public.reviews r CROSS JOIN LATERAL jsonb_array_elements_text(r.selected_keywords) v(name)
  LEFT JOIN public.review_keywords k ON k.name=v.name WHERE k.id IS NULL) THEN
  RAISE EXCEPTION '기존 선택값에 대응하는 키워드 원본이 없습니다.';
 END IF;
INSERT INTO public.review_keyword_selections(review_id,keyword_id,created_at,updated_at)
 SELECT DISTINCT r.id,k.id,r.created_at,r.updated_at FROM public.reviews r
 CROSS JOIN LATERAL jsonb_array_elements_text(r.selected_keywords) v(name)
 JOIN public.review_keywords k ON k.name=v.name
ON CONFLICT(review_id,keyword_id) DO NOTHING;
 END IF;
END $$;
COMMIT;
