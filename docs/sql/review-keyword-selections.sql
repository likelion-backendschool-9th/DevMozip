-- reviews/review_keywords 다대다 연결. 원본 리뷰 이름 배열은 과거 표시용 스냅샷으로 보존한다.
BEGIN;
CREATE TABLE IF NOT EXISTS public.review_keyword_selections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES public.reviews(id),
 keyword_id BIGINT NOT NULL REFERENCES public.review_keywords(id),
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
 UNIQUE(review_id, keyword_id)
);
CREATE INDEX IF NOT EXISTS review_keyword_selections_keyword_idx ON public.review_keyword_selections(keyword_id);
INSERT INTO public.review_keywords(name) VALUES
