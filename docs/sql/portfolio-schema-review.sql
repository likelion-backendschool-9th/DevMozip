-- reports와 같은 IDENTITY/TIMESTAMP/외래키 형식으로 기존 ERD 컬럼을 매핑한다.
-- 이미 portfolios가 있으면 오류로 중단한다. 기존 테이블·지원서·데이터 변경 없음.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    title VARCHAR(255) NOT NULL,
    thumbnail_url VARCHAR(2048),
    topic VARCHAR(255),
    summary TEXT,
    description TEXT, -- 일반 텍스트 또는 devmozip.portfolio.v1 편집 문서 JSON
    role VARCHAR(100),
    tech_stack JSONB,
    attachments JSONB,
    visibility VARCHAR(20) NOT NULL DEFAULT 'PRIVATE', -- PUBLIC / PRIVATE
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX portfolios_user_created_idx
    ON public.portfolios(user_id, created_at DESC, id DESC);

COMMENT ON TABLE public.portfolios IS '사용자 원본 포트폴리오. 프로젝트 제출 연결/스냅샷과 별도';
COMMENT ON COLUMN public.portfolios.user_id IS '작성자 사용자 ID';
COMMENT ON COLUMN public.portfolios.thumbnail_url IS '서버에 저장한 대표 이미지 경로';
COMMENT ON COLUMN public.portfolios.topic IS '대표 주제/분야';
COMMENT ON COLUMN public.portfolios.summary IS '한 줄 소개';
COMMENT ON COLUMN public.portfolios.description IS '상세 설명 또는 버전 있는 편집 문서. 저장 형식은 담당자 확인 필요';
COMMENT ON COLUMN public.portfolios.role IS '담당 역할';
COMMENT ON COLUMN public.portfolios.tech_stack IS '사용 기술 스택 문자열 배열';
COMMENT ON COLUMN public.portfolios.attachments IS '서버 저장 파일의 식별자/경로 등 첨부 메타데이터. 파일 바이너리 아님';
COMMIT;

