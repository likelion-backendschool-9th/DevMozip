-- Stage 4 PostgreSQL schema. Apply explicitly after reviewing the existing schema.
-- Existing users/projects/conversations/messages must already exist. No automatic startup execution.
BEGIN;
CREATE TABLE ai_recommendation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id),
    ai_message_id BIGINT REFERENCES ai_messages(id),
    conditions JSONB NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_ai_request_key UNIQUE (ai_conversation_id, idempotency_key),
    CONSTRAINT ck_ai_request_state CHECK (
        (status = 'PENDING' AND completed_at IS NULL)
        OR (status IN ('SUCCESS', 'FAILED') AND completed_at IS NOT NULL)
    )
);
CREATE INDEX ix_ai_request_latest ON ai_recommendation_requests(ai_conversation_id, created_at DESC, id DESC);
CREATE INDEX ix_ai_request_message ON ai_recommendation_requests(ai_message_id);
CREATE TABLE ai_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommended_request_id BIGINT NOT NULL REFERENCES ai_recommendation_requests(id),
    recommended_user_id BIGINT REFERENCES users(id),
    recommended_project_id BIGINT REFERENCES projects(id),
    match_score NUMERIC(5,2) NOT NULL CHECK (match_score BETWEEN 0 AND 100),
    basic_reason TEXT NOT NULL,
    detailed_reason TEXT,
    rank INTEGER NOT NULL CHECK (rank >= 1),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_ai_result_target CHECK (
        (recommended_user_id IS NOT NULL AND recommended_project_id IS NULL)
        OR (recommended_user_id IS NULL AND recommended_project_id IS NOT NULL)
    ),
    CONSTRAINT uk_ai_result_user UNIQUE (recommended_request_id, recommended_user_id),
    CONSTRAINT uk_ai_result_project UNIQUE (recommended_request_id, recommended_project_id)
);
CREATE UNIQUE INDEX uk_ai_result_user_rank ON ai_recommendations(recommended_request_id, rank)
    WHERE recommended_user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_ai_result_project_rank ON ai_recommendations(recommended_request_id, rank)
    WHERE recommended_project_id IS NOT NULL;
-- Target FKs also need indexes for parent deletion checks.
CREATE INDEX ix_ai_result_user ON ai_recommendations(recommended_user_id);
CREATE INDEX ix_ai_result_project ON ai_recommendations(recommended_project_id);
-- analysis_level deferred until stage 6; no input_hash or recommendation_type.
-- All FKs use NO ACTION. Service deletion: results → requests → messages → conversation.
COMMIT;
