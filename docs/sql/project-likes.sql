-- 사용자 확정: bookmarks와 동일한 공통 likes 구조. 프로젝트 전용 테이블을 별도로 만들지 않는다.
-- 사용자는 인증된 users.id, 프로젝트는 projects.id를 참조한다.
-- post_id는 공통 게시글 담당자의 테이블/FK 계약이 확정되면 연결한다.
BEGIN;
CREATE TABLE IF NOT EXISTS public.likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES public.users(id),
 project_id BIGINT REFERENCES public.projects(id),
 post_id BIGINT,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 UNIQUE(user_id,project_id),
 UNIQUE(user_id,post_id),
 CHECK(num_nonnulls(project_id,post_id)=1)
);
COMMIT;
