@SpringBootTest(properties="project.current-user.development-enabled=false") @AutoConfigureMockMvc @ActiveProfiles("test") @Testcontainers(disabledWithoutDocker=true)
class ProjectPortfolioLinkIntegrationTest {
	@Container @ServiceConnection static PostgreSQLContainer postgres=new PostgreSQLContainer("postgres:17");
	@Autowired MockMvc mvc; @Autowired JdbcTemplate jdbc; @Autowired JwtProvider jwt; @Autowired ObjectMapper mapper;
	@MockitoBean RefreshTokenStore refresh;
	@MockitoBean(name="projectClock") Clock clock;
	@MockitoSpyBean ProjectPortfolioRepository portfolios;
	String token(long id){return "Bearer "+jwt.createAccessToken(id+"@link.test",id==101?"PREMIUM":"USER");}
	@BeforeEach void fixtures() throws Exception {
		jdbc.execute("CREATE TABLE IF NOT EXISTS portfolios(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),title VARCHAR(255) NOT NULL,thumbnail_url VARCHAR(2048),topic VARCHAR(255),summary TEXT,description TEXT,role VARCHAR(100),tech_stack JSONB,attachments JSONB,visibility VARCHAR(20) NOT NULL,created_at TIMESTAMP NOT NULL,updated_at TIMESTAMP NOT NULL)");
		jdbc.update("DELETE FROM project_application_portfolios");jdbc.update("DELETE FROM project_applications");jdbc.update("DELETE FROM project_members");jdbc.update("DELETE FROM projects");jdbc.update("DELETE FROM portfolios");jdbc.update("DELETE FROM users");
		jdbc.execute(Files.readString(Path.of("../docs/sql/project-portfolio-reference.sql")));
		for(long id:new long[]{101,202,303})jdbc.update("INSERT INTO users(id,email,nickname,tag,role,status) VALUES(?,?,?,?,?,?)",id,id+"@link.test","개발자"+id,"link-"+id,id==101?"PREMIUM":"USER","ACTIVE");
		when(clock.getZone()).thenReturn(ZoneId.of("Asia/Seoul"));when(clock.instant()).thenReturn(Instant.parse("2026-11-06T03:00:00Z"));
	}
	Map<String,Object> input(){return new LinkedHashMap<>(Map.of("title","지원 포트폴리오","summary","한 줄 소개","role","백엔드","techStack",List.of("Java"),"description","제출 당시의 프로젝트 설명","visibility","PUBLIC"));}
	JsonNode portfolio(long user,String visibility) throws Exception {
		var value=input();value.put("visibility",visibility);
		return mapper.readTree(mvc.perform(post("/api/v1/portfolios").header("Authorization",token(user)).contentType("application/json").content(mapper.writeValueAsString(value))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString());
	}
	long id(JsonNode p){return p.path("portfolio").path("id").asLong();}
	long project() throws Exception {
		var body=new LinkedHashMap<String,Object>(Map.of("title","포트폴리오 연동 프로젝트","description","실제 포트폴리오를 연결합니다.","imageUrl","https://example.test/a.png","isPublic",true,"recruitmentSlots",List.of(Map.of("roleCode","BACKEND","capacity",3,"minimumYears",0)),"techStacks",List.of("Java"),"interests",List.of("교육"),"recruitmentStart","2026-11-01","recruitmentEnd","2026-11-20","developmentStart","2026-11-06"));body.put("developmentEnd","2026-12-30");
		return mapper.readTree(mvc.perform(post("/api/v1/projects").header("Authorization",token(101)).contentType("application/json").content(mapper.writeValueAsString(body))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).path("id").asLong();
	}
	org.springframework.test.web.servlet.ResultActions apply(long project,List<Long> ids) throws Exception {
		return mvc.perform(post("/api/v1/projects/"+project+"/applications").header("Authorization",token(202)).contentType("application/json").content(mapper.writeValueAsString(Map.of("jobRole","BACKEND","portfolioIds",ids,"introduction","프로젝트에 함께 참여하고 싶습니다."))));
	}
	org.springframework.test.web.servlet.ResultActions edit(JsonNode before) throws Exception {
		var value=input();value.put("description","변경한 설명");value.put("expectedUpdatedAt",before.path("portfolio").path("updatedAt").asString());
		return mvc.perform(put("/api/v1/portfolios/"+id(before)).header("Authorization",token(202)).contentType("application/json").content(mapper.writeValueAsString(value)));
	}
	@Test void onlyOwnPublicPortfoliosAreEligible() throws Exception {
		long project=project();var own=portfolio(202,"PUBLIC");var hidden=portfolio(202,"PRIVATE");var foreign=portfolio(303,"PUBLIC");
		mvc.perform(get("/api/v1/projects/"+project+"/application-options").header("Authorization",token(202))).andExpect(status().isOk()).andExpect(jsonPath("$.canApply").value(true)).andExpect(jsonPath("$.portfolios.length()").value(1)).andExpect(jsonPath("$.portfolios[0].id").value(id(own)));
		for(long invalid:new long[]{id(hidden),id(foreign),999999})apply(project,List.of(invalid)).andExpect(status().isForbidden());
		apply(project,List.of(id(own),id(own))).andExpect(status().isBadRequest());
		assertEquals(0,jdbc.queryForObject("SELECT count(*) FROM project_application_portfolios",Integer.class));
		assertTrue(mapper.readTree(mvc.perform(get("/api/v1/portfolios/"+id(own)).header("Authorization",token(202))).andReturn().getResponse().getContentAsString()).path("canEdit").asBoolean());
	}
	@Test void emptyEligibleListExplainsWhyApplicationIsDisabled() throws Exception {
		long project=project();portfolio(202,"PRIVATE");
		mvc.perform(get("/api/v1/projects/"+project+"/application-options").header("Authorization",token(202))).andExpect(status().isOk()).andExpect(jsonPath("$.canApply").value(false)).andExpect(jsonPath("$.portfolios.length()").value(0));
	}
	@Test void submissionPermanentlyLocksOriginalEvenAfterCancellation() throws Exception {
		long project=project();var p=portfolio(202,"PUBLIC");
		long application=mapper.readTree(apply(project,List.of(id(p))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).path("id").asLong();
		mvc.perform(get("/api/v1/portfolios/"+id(p)).header("Authorization",token(202))).andExpect(status().isOk()).andExpect(jsonPath("$.canEdit").value(false)).andExpect(jsonPath("$.submitted").value(true));
		edit(p).andExpect(status().isConflict());
		mvc.perform(delete("/api/v1/portfolios/"+id(p)).header("Authorization",token(202))).andExpect(status().isConflict());
		mvc.perform(patch("/api/v1/projects/"+project+"/applications/"+application).header("Authorization",token(202)).contentType("application/json").content("{\"status\":\"CANCELLED\"}")).andExpect(status().isOk());
		edit(p).andExpect(status().isConflict());assertEquals("제출 당시의 프로젝트 설명",jdbc.queryForObject("SELECT description FROM portfolios WHERE id=?",String.class,id(p)));
		apply(project,List.of(id(p))).andExpect(status().isConflict());
	}
	@Test void acceptsThreeAndRejectsFourAndRetainsLockAfterRejection() throws Exception {
		long project=project();var one=portfolio(202,"PUBLIC");var two=portfolio(202,"PUBLIC");var three=portfolio(202,"PUBLIC");var four=portfolio(202,"PUBLIC");
		apply(project,List.of(id(one),id(two),id(three),id(four))).andExpect(status().isBadRequest());
		long application=mapper.readTree(apply(project,List.of(id(one),id(two),id(three))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString()).path("id").asLong();
		mvc.perform(patch("/api/v1/projects/"+project+"/applications/"+application).header("Authorization",token(101)).contentType("application/json").content("{\"status\":\"REJECTED\",\"rejectionReason\":\"다음 기회에 함께해요.\"}")).andExpect(status().isOk());
		edit(one).andExpect(status().isConflict());edit(four).andExpect(status().isOk());
	}
	@Test void concurrentEditWaitsForSubmissionThenFails() throws Exception {
		long project=project();var p=portfolio(202,"PUBLIC");var locked=new CountDownLatch(1);var release=new CountDownLatch(1);
		doAnswer(invocation->{var result=invocation.callRealMethod();locked.countDown();assertTrue(release.await(15,TimeUnit.SECONDS));return result;}).when(portfolios).lockOwnedPublic(eq(202L),anyList());
		try(var executor=Executors.newFixedThreadPool(2)){
			var submission=executor.submit(()->apply(project,List.of(id(p))).andReturn().getResponse().getStatus());assertTrue(locked.await(15,TimeUnit.SECONDS));
			var editing=executor.submit(()->edit(p).andReturn().getResponse().getStatus());
			assertThrows(TimeoutException.class,()->editing.get(250,TimeUnit.MILLISECONDS));release.countDown();
			assertEquals(201,submission.get(15,TimeUnit.SECONDS));assertEquals(409,editing.get(15,TimeUnit.SECONDS));
		}finally{release.countDown();}
	}
	@Test void missingForeignKeyDisablesApplication() throws Exception {
		long project=project();var p=portfolio(202,"PUBLIC");jdbc.execute("ALTER TABLE project_application_portfolios DROP CONSTRAINT fk_project_application_portfolio");
		try{apply(project,List.of(id(p))).andExpect(status().isServiceUnavailable());assertEquals(0,jdbc.queryForObject("SELECT count(*) FROM project_applications",Integer.class));}
		finally{jdbc.execute(Files.readString(Path.of("../docs/sql/project-portfolio-reference.sql")));}
	}
}
