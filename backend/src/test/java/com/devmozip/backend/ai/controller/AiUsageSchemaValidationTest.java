package com.devmozip.backend.ai.controller;

import com.devmozip.backend.entity.AiUsage;
import java.sql.DriverManager;
import java.util.UUID;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AiUsageSchemaValidationTest {
	@Test void existingCharSevenColumnPassesHibernateValidate() throws Exception {
		String configured = System.getenv("DEVMOZIP_AI_USAGE_TEST_JDBC_URL");
		String url = configured == null ? "jdbc:h2:mem:ai-usage-validation;MODE=PostgreSQL;DB_CLOSE_DELAY=-1" : configured;
		String username = configured == null ? "sa" : "ai_engine_test";
		String schema = "ai_usage_validation_" + UUID.randomUUID().toString().replace("-", "");
		try (var connection = DriverManager.getConnection(url, username, ""); var sql = connection.createStatement()) {
			sql.execute("CREATE SCHEMA " + schema);
			try {
				sql.execute("CREATE TABLE " + schema + ".ai_usages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
					+ "user_id BIGINT NOT NULL, usage_month CHAR(7) NOT NULL, used_count INT NOT NULL DEFAULT 0,"
					+ "pending_count INT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)");
				var registry = new StandardServiceRegistryBuilder()
					.applySetting("hibernate.connection.url", url)
					.applySetting("hibernate.connection.username", username)
					.applySetting("hibernate.connection.password", "")
					.applySetting("hibernate.default_schema", schema)
					.applySetting("hibernate.hbm2ddl.auto", "validate")
					.build();
				try (var factory = new MetadataSources(registry).addAnnotatedClass(AiUsage.class).buildMetadata().buildSessionFactory()) {
					assertTrue(factory.isOpen());
				} finally { StandardServiceRegistryBuilder.destroy(registry); }
			} finally { sql.execute("DROP SCHEMA " + schema + " CASCADE"); }
		}
	}
}
