	@Test void sameKeyConcurrentCallsHaveOneReservationAndOneExecution() throws Exception {
		var entered = new CountDownLatch(1); var release = new CountDownLatch(1);
		when(engine.recommend(any(), any())).thenAnswer(call -> { entered.countDown(); assertTrue(release.await(15, TimeUnit.SECONDS)); return EMPTY; });
		try (var pool = Executors.newFixedThreadPool(2)) {
			var first = pool.submit(() -> recommend(conversationId, "same").andReturn().getResponse().getStatus());
			try {
				assertTrue(entered.await(15, TimeUnit.SECONDS));
				recommend(conversationId, "same").andExpect(status().isAccepted()); counts(0, 1);
			} finally { release.countDown(); }
			assertEquals(201, first.get(15, TimeUnit.SECONDS));
		}
		counts(1, 0); verify(engine, times(1)).recommend(any(), any());
	}
	@Test void differentConversationsCompeteForLastSlotWithoutOverspending() throws Exception {
		for (int i = 0; i < 4; i++) success("initial-" + i);
		var ids = new ArrayList<Long>(); for (int i = 0; i < 8; i++) ids.add(conversation());
		var ready = new CountDownLatch(8); var start = new CountDownLatch(1);
		try (var pool = Executors.newFixedThreadPool(8)) {
			var futures = new ArrayList<Future<Integer>>();
			for (long id : ids) futures.add(pool.submit(() -> { ready.countDown(); assertTrue(start.await(15, TimeUnit.SECONDS)); return recommend(id, "last").andReturn().getResponse().getStatus(); }));
			assertTrue(ready.await(15, TimeUnit.SECONDS)); start.countDown();
			int successful = 0, rejected = 0;
			for (var f : futures) { int code = f.get(30, TimeUnit.SECONDS); if (code == 201) successful++; else if (code == 429) rejected++; else fail("Unexpected HTTP " + code); }
			assertEquals(1, successful); assertEquals(7, rejected);
		}
		counts(5, 0);
	}
	@Test void firstMonthCreationRaceHasOneRowAndAtMostFiveSuccesses() throws Exception {
		var ids = new ArrayList<Long>(); for (int i = 0; i < 8; i++) ids.add(conversation());
		var ready = new CountDownLatch(8); var start = new CountDownLatch(1);
		try (var pool = Executors.newFixedThreadPool(8)) {
			var futures = new ArrayList<Future<Integer>>();
			for (long id : ids) futures.add(pool.submit(() -> { ready.countDown(); start.await(); return recommend(id, "first-month").andReturn().getResponse().getStatus(); }));
			assertTrue(ready.await(15, TimeUnit.SECONDS)); start.countDown();
			int successful = 0;
			for (var f : futures) { int code = f.get(30, TimeUnit.SECONDS); assertTrue(code == 201 || code == 429, "HTTP " + code); if (code == 201) successful++; }
			assertEquals(5, successful);
		}
		assertEquals(1L, jdbc.queryForObject("SELECT count(*) FROM ai_usages", Long.class)); counts(5, 0);
	}
