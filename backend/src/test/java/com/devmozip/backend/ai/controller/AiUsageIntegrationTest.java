	@Test void expirationAndCompletionRaceNeverDoubleSettles() throws Exception {
		var entered = new CountDownLatch(1); var release = new CountDownLatch(1);
		when(engine.recommend(any(), any())).thenAnswer(call -> { entered.countDown(); assertTrue(release.await(15, TimeUnit.SECONDS)); return EMPTY; });
		try (var pool = Executors.newFixedThreadPool(3)) {
			var running = pool.submit(() -> recommend(conversationId, "race-expiry").andReturn().getResponse().getStatus());
			try {
				assertTrue(entered.await(15, TimeUnit.SECONDS));
				when(clock.instant()).thenReturn(START.plus(Duration.ofMinutes(31)));
				var cleaner1 = pool.submit(() -> usage.expire(userId));
				var cleaner2 = pool.submit(() -> usage.expire(userId));
				release.countDown();
				cleaner1.get(15, TimeUnit.SECONDS); cleaner2.get(15, TimeUnit.SECONDS);
			} finally { release.countDown(); }
			assertEquals(500, running.get(15, TimeUnit.SECONDS));
		}
		counts(0, 0);
		assertEquals("FAILED", jdbc.queryForObject("SELECT status FROM ai_recommendation_requests", String.class));
	}
