package com.devmozip.backend.controller;

import com.devmozip.backend.security.jwt.*;
import com.devmozip.backend.storage.ProfileImageTestFiles;
import java.nio.file.Path;
import java.util.Map;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.*;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;
import org.testcontainers.junit.jupiter.*;
import org.testcontainers.postgresql.PostgreSQLContainer;
import tools.jackson.databind.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest @AutoConfigureMockMvc @ActiveProfiles("test") @Testcontainers(disabledWithoutDocker=true)
class PortfolioFileIntegrationTest {
    @Container @ServiceConnection static PostgreSQLContainer postgres=new PostgreSQLContainer("postgres:17");
    @TempDir static Path files;
    @Autowired MockMvc mvc; @Autowired JdbcTemplate jdbc; @Autowired JwtProvider jwt; @Autowired ObjectMapper mapper;
    @MockitoBean RefreshTokenStore refresh;
    @DynamicPropertySource static void properties(DynamicPropertyRegistry r) {
        r.add("spring.jpa.hibernate.ddl-auto",()->"create");r.add("spring.sql.init.mode",()->"never");r.add("portfolio.files.directory",()->files.toString());
    }
    @BeforeEach void fixture() {
        assertNotEquals(5442,postgres.getMappedPort(5432));
        jdbc.execute("CREATE TABLE IF NOT EXISTS portfolios(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT,title TEXT,thumbnail_url TEXT,topic TEXT,summary TEXT,description TEXT,role TEXT,tech_stack JSONB,attachments JSONB,visibility TEXT,created_at TIMESTAMP,updated_at TIMESTAMP)");
        jdbc.update("DELETE FROM portfolios");jdbc.update("DELETE FROM users");
        for(int id=1;id<=4;id++)jdbc.update("INSERT INTO users(id,email,nickname,tag,role,status) VALUES(?,?,?,?,?,?)",id,"file"+id+"@test.local","파일회원"+id,"file-"+id,id==2?"PREMIUM":"USER",id==4?"SUSPENDED":"ACTIVE");
    }
    String auth(int id){return "Bearer "+jwt.createAccessToken("file"+id+"@test.local","USER");}
    MockMultipartFile png()throws Exception{return new MockMultipartFile("file","화면.png","image/png",ProfileImageTestFiles.png());}
    JsonNode upload()throws Exception{return mapper.readTree(mvc.perform(multipart("/api/v1/files").file(png()).header("Authorization",auth(1))).andExpect(status().isCreated()).andReturn().getResponse().getContentAsString());}
    @Test void ordinaryMemberCanUploadAndOnlyOwnerReadsUnattachedFile()throws Exception{
        mvc.perform(multipart("/api/v1/files").file(png())).andExpect(status().isUnauthorized());
        mvc.perform(multipart("/api/v1/files").file(png()).header("Authorization",auth(4))).andExpect(status().isForbidden());
        var file=upload();String url="/api/v1/files/"+file.get("id").asString();
        mvc.perform(get(url).header("Authorization",auth(1))).andExpect(status().isOk()).andExpect(header().string("Cache-Control","no-store"));
        mvc.perform(get(url)).andExpect(status().isNotFound());mvc.perform(get(url).header("Authorization",auth(2))).andExpect(status().isNotFound());
        assertTrue(file.get("url").asString().startsWith("/api/files/"));assertFalse(file.has("ownerId"));
    }
    @Test void onlyPublishedCoverIsAnonymousAndPrivateChangeRevokesIt()throws Exception{
        var file=upload();String url="/api/v1/files/"+file.get("id").asString();
        jdbc.update("INSERT INTO portfolios(id,user_id,thumbnail_url,visibility) VALUES(1,1,?,'PUBLIC')",file.get("url").asString());
        mvc.perform(get(url)).andExpect(status().isOk()).andExpect(content().contentType("image/png"));
        mvc.perform(patch("/api/v1/portfolios/1/visibility").header("Authorization",auth(1)).contentType("application/json").content("{\"visibility\":\"PRIVATE\",\"expectedUpdatedAt\":null}")).andExpect(status().isOk());
        mvc.perform(get(url)).andExpect(status().isNotFound());
        mvc.perform(get(url).header("Authorization",auth(1))).andExpect(status().isOk());
    }
    @Test void publicBodyRequiresPremiumAndOriginalUploaderReference()throws Exception{
        var file=upload();String url="/api/v1/files/"+file.get("id").asString();
        jdbc.update("INSERT INTO portfolios(id,user_id,description,visibility) VALUES(1,3,?,'PUBLIC')",file.get("url").asString());
        mvc.perform(get(url).header("Authorization",auth(2))).andExpect(status().isNotFound());
        jdbc.update("UPDATE portfolios SET user_id=1 WHERE id=1");
        mvc.perform(get(url).header("Authorization",auth(2))).andExpect(status().isOk());
        mvc.perform(get(url).header("Authorization",auth(3))).andExpect(status().isNotFound());mvc.perform(get(url)).andExpect(status().isNotFound());
        jdbc.update("UPDATE users SET status='SUSPENDED' WHERE id=1");mvc.perform(get(url).header("Authorization",auth(2))).andExpect(status().isNotFound());
    }
    @Test void metadataIsSavedWithPortfolioAndOtherOwnerCannotAttachIt()throws Exception{
        var file=upload();
        var body=Map.of("title","파일 연결","summary","요약","role","개발자","techStack",java.util.List.of("Java"),"attachments",java.util.List.of(Map.of("name",file.get("name").asString(),"url",file.get("url").asString())));
        mvc.perform(post("/api/v1/portfolios").header("Authorization",auth(3)).contentType("application/json").content(mapper.writeValueAsString(body))).andExpect(status().isForbidden());
        mvc.perform(post("/api/v1/portfolios").header("Authorization",auth(1)).contentType("application/json").content(mapper.writeValueAsString(body)))
                .andExpect(status().isCreated()).andExpect(jsonPath("$.attachments[0].url").value(file.get("url").asString()));
        assertEquals(1,jdbc.queryForObject("SELECT count(*) FROM portfolios WHERE user_id=1",Integer.class));
    }
    @Test void pdfDownloadsAndTamperedIdsAreRejected()throws Exception{
        var r=mvc.perform(multipart("/api/v1/files").file(new MockMultipartFile("file","자료.pdf","application/pdf","%PDF-1.7\n%%EOF".getBytes())).header("Authorization",auth(1)))
                .andExpect(status().isCreated()).andReturn().getResponse();var file=mapper.readTree(r.getContentAsString());
        mvc.perform(get("/api/v1/files/"+file.get("id").asString()).header("Authorization",auth(1))).andExpect(status().isOk()).andExpect(header().string("Content-Disposition",org.hamcrest.Matchers.startsWith("attachment;"))).andExpect(header().string("X-Content-Type-Options","nosniff"));
        mvc.perform(get("/api/v1/files/not-a-uuid")).andExpect(status().isNotFound());
        mvc.perform(multipart("/api/v1/files").header("Authorization",auth(1))).andExpect(status().isBadRequest());
    }
}
