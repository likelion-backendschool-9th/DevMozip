            for(var value:List.of(a,b))results.add(executor.submit(()->{latch.await();return mvc.perform(put(PATH+"/"+id).header("Authorization",token(1)).contentType("application/json").content(mapper.writeValueAsString(value))).andReturn().getResponse().getStatus();}));
