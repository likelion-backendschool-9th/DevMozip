-- Isolated H2 fixture for conversation tests. Recommendation tables allow stage 4 deletion; no usage table.
CREATE TABLE users (id BIGINT PRIMARY KEY);
CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(255), current_conditions JSON, client_key VARCHAR(128),
    UNIQUE(user_id, client_key),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id),
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content TEXT NOT NULL, client_key VARCHAR(128),
    UNIQUE(conversation_id, client_key),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE ai_recommendation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id),
    ai_message_id BIGINT REFERENCES ai_messages(id),
    conditions JSON NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_ai_request_key UNIQUE (ai_conversation_id, idempotency_key)
);
CREATE TABLE ai_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommended_request_id BIGINT NOT NULL REFERENCES ai_recommendation_requests(id),
    recommended_user_id BIGINT REFERENCES users(id),
    recommended_project_id BIGINT,
    match_score NUMERIC(5,2) NOT NULL,
    basic_reason TEXT NOT NULL, detailed_reason TEXT, rank INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
